import type { Context, Hono } from 'hono'
import { LOCALES, localizedPath, switchLocalePath, type Locale } from '../lib/i18n'
import type { AppEnv } from './types'

/** Handler for a public page. It runs only for locale-prefixed URLs. */
export type PageHandler<P extends string = string> = (c: Context<AppEnv, P>) => Response | Promise<Response>

/** `/articles` → `/en/articles`, `/` → `/id`. */
export function prefixedPath(locale: Locale, path: string): string {
  return path === '/' ? `/${locale}` : `/${locale}${path}`
}

/**
 * Routes that live outside the localized public tree. Their URLs must never
 * receive a language prefix when a switcher redirects back to them.
 */
export function isUnlocalizedPath(path: string): boolean {
  return (
    path === '/admin' ||
    path.startsWith('/admin/') ||
    path.startsWith('/api/') ||
    path.startsWith('/uploads/') ||
    path.startsWith('/assets/') ||
    path === '/rss.xml' ||
    path === '/feed.xml' ||
    path === '/sitemap.xml' ||
    path === '/robots.txt' ||
    path === '/llms.txt' ||
    path === '/locale'
  )
}

/**
 * Rewrites a same-site path for a locale without touching admin, API or asset
 * URLs. Query strings and fragments already present in the path are preserved.
 */
export function localizedTarget(path: string, locale: Locale): string {
  if (isUnlocalizedPath(path)) return path
  return switchLocalePath(path, locale)
}

function legacyRedirect(c: Context<AppEnv>): Response {
  const locale = c.get('locale')
  const search = new URL(c.req.url).search
  // The negotiation depends on cookies and headers, so shared caches must not
  // replay this redirect for a different visitor.
  c.header('Cache-Control', 'private, no-store')
  c.header('Vary', 'Accept-Language, Cookie')
  return c.redirect(`${localizedPath(locale, c.req.path)}${search}`, 302)
}

/**
 * Registers a public page three times: the canonical `/id` and `/en` URLs plus
 * a backwards-compatible prefix-free URL that redirects to the negotiated
 * language. Existing links and bookmarks keep working.
 */
export function page<P extends string>(app: Hono<AppEnv>, path: P, handler: PageHandler<P>): void {
  app.get(path, legacyRedirect)
  for (const locale of LOCALES) {
    app.get(prefixedPath(locale, path) as P, handler as PageHandler<P>)
  }
}

/**
 * Registers a form action that exists on the public tree. Unlike `page`, it
 * answers on the locale-prefixed URLs as well as the legacy prefix-free one, so
 * links generated by emails (which include a locale) can post back.
 */
export function action<P extends string>(app: Hono<AppEnv>, path: P, handler: PageHandler<P>): void {
  app.post(path, legacyRedirect as PageHandler<P>)
  for (const locale of LOCALES) {
    app.post(prefixedPath(locale, path) as P, handler as PageHandler<P>)
  }
}
